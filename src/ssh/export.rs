use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};

use crate::config;
use crate::store::{HostSource, LauncherStore, ManagedHost};

const EXPORT_HEADER: &str = "# Generated by SSHub — do not edit by hand\n";

/// Default export path: `config_dir()/exported.conf`.
pub fn exported_conf_path() -> Result<PathBuf> {
    Ok(config::config_dir()?.join("exported.conf"))
}

/// Export path inside an explicit directory (profile-aware variant).
pub fn exported_conf_path_in(dir: &Path) -> PathBuf {
    dir.join("exported.conf")
}

/// Write launcher-native hosts to `path` using atomic replace + `.bak` backup.
pub fn export_launcher_hosts_to(store: &LauncherStore, path: &Path) -> Result<PathBuf> {
    let content = render_launcher_hosts(store)?;
    atomic_write_with_backup(path, &content)?;
    Ok(path.to_path_buf())
}

/// Write launcher-native hosts to `exported.conf` using atomic replace + `.bak` backup.
pub fn export_launcher_hosts(store: &LauncherStore) -> Result<PathBuf> {
    let path = exported_conf_path()?;
    export_launcher_hosts_to(store, &path)
}

/// Render launcher-native hosts as ssh_config text (no file write).
pub fn render_launcher_hosts(store: &LauncherStore) -> Result<String> {
    let hosts = store.list_hosts_filtered(Some(HostSource::Launcher))?;
    let mut out = String::from(EXPORT_HEADER);
    for host in hosts {
        // Materialize the effective values: an exported static config cannot
        // express inheritance, so group defaults are baked into each block.
        // Fail closed: a row that does not resolve or validate is never
        // written, since every later `ssh` run would read the file.
        let resolved = store
            .resolve_connection(&host)
            .with_context(|| format!("host '{}'", host.name))?;
        out.push_str(
            &render_host_block(&host, &resolved)
                .with_context(|| format!("host '{}' cannot be exported", host.name))?,
        );
        out.push('\n');
    }
    Ok(out)
}

/// A value for a single-token ssh_config field (`Host` pattern, `HostName`,
/// `User`): no whitespace/control/quote/`#` that would split or end the line,
/// plus (for the `Host` line) none of the pattern characters `*?!,`.
fn token(field: &str, s: &str, pattern: bool) -> Result<String> {
    let bad = |c: char| {
        c.is_whitespace()
            || c.is_control()
            || matches!(c, '"' | '\'' | '\\' | '#')
            || (pattern && matches!(c, '*' | '?' | '!' | ','))
    };
    if s.is_empty() || s.starts_with('-') || s.contains(bad) {
        anyhow::bail!("{field} {s:?} is not safe to write into ssh_config");
    }
    Ok(s.replace('%', "%%"))
}

/// A path field (`IdentityFile`, `CertificateFile`): quoted when it has
/// spaces, `%` doubled so ssh does not expand tokens.
fn path_val(field: &str, p: &Path) -> Result<String> {
    let s = p.to_string_lossy();
    if s.contains(|c: char| c.is_control()) {
        anyhow::bail!("{field} {s:?} contains control characters");
    }
    let s = s.replace('%', "%%");
    Ok(
        if s.contains(|c: char| c.is_whitespace() || matches!(c, '"' | '\\')) {
            format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
        } else {
            s
        },
    )
}

fn render_host_block(
    host: &ManagedHost,
    resolved: &crate::store::ResolvedConnection,
) -> Result<String> {
    let mut lines = vec![format!("Host {}", token("name", &host.name, true)?)];
    lines.push(format!(
        "    HostName {}",
        token("address", &host.address, false)?
    ));

    let user = resolved.username.as_deref().or_else(|| {
        resolved
            .identity
            .as_ref()
            .and_then(|i| i.username.as_deref())
    });
    if let Some(user) = user {
        lines.push(format!("    User {}", token("username", user, false)?));
    }

    if resolved.port != 22 {
        lines.push(format!("    Port {}", resolved.port));
    }

    if let Some(key) = resolved
        .identity
        .as_ref()
        .and_then(|i| i.private_key.as_ref())
    {
        lines.push(format!(
            "    IdentityFile {}",
            path_val("IdentityFile", key)?
        ));
    }

    if let Some(cert) = resolved
        .identity
        .as_ref()
        .and_then(|i| i.certificate.as_ref())
    {
        lines.push(format!(
            "    CertificateFile {}",
            path_val("CertificateFile", cert)?
        ));
    }

    if let Some(jump) = &resolved.proxy_jump {
        if !jump.is_empty() {
            if let Some(problem) = crate::map::hops::jump_problem(jump) {
                anyhow::bail!("{problem}");
            }
            lines.push(format!("    ProxyJump {jump}"));
        }
    }

    if resolved.forward_agent {
        lines.push("    ForwardAgent yes".to_string());
    }

    if let Some(cmd) = &host.remote_command {
        if !cmd.is_empty() {
            if cmd.contains(|c: char| c.is_control()) {
                anyhow::bail!("remote command contains control characters");
            }
            lines.push(format!(
                "    {}",
                crate::ssh::host::format_ssh_config_option(
                    "RemoteCommand",
                    &cmd.replace('%', "%%")
                )
            ));
        }
    }

    Ok(lines.join("\n"))
}

/// Write `content` to `path` atomically, backing up an existing file to `path.bak`.
pub fn atomic_write_with_backup(path: &Path, content: &str) -> Result<()> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)
            .with_context(|| format!("create export directory {}", parent.display()))?;
    }

    let tmp = path.with_extension("conf.tmp");
    fs::write(&tmp, content)
        .with_context(|| format!("write temporary export file {}", tmp.display()))?;

    if path.exists() {
        let bak = backup_path(path);
        fs::copy(path, &bak)
            .with_context(|| format!("backup {} to {}", path.display(), bak.display()))?;
    }

    fs::rename(&tmp, path)
        .with_context(|| format!("rename {} to {}", tmp.display(), path.display()))?;
    Ok(())
}

fn backup_path(path: &Path) -> PathBuf {
    PathBuf::from(format!("{}.bak", path.display()))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::store::{LauncherStore, NewHost};

    #[test]
    fn render_includes_identity_and_connection_fields() {
        let store = LauncherStore::open_in_memory().unwrap();
        let default_id = store.get_identity_by_name("Default").unwrap().unwrap().id;
        store
            .update_identity(
                default_id,
                &crate::store::IdentityUpdate {
                    username: Some(Some("admin".into())),
                    private_key: Some(Some(PathBuf::from("/home/user/.ssh/id_ed25519"))),
                    ..Default::default()
                },
            )
            .unwrap();

        store
            .create_host(&NewHost {
                name: "dev-partners".into(),
                label: Some("Dev Partners".into()),
                address: "10.100.19.123".into(),
                port: Some(22),
                group_id: None,
                identity_id: Some(default_id),
                tags: vec![],
                notes: None,
                ..Default::default()
            })
            .unwrap();

        let content = render_launcher_hosts(&store).unwrap();
        assert!(content.contains("Host dev-partners"));
        assert!(content.contains("HostName 10.100.19.123"));
        assert!(content.contains("User admin"));
        assert!(content.contains("IdentityFile /home/user/.ssh/id_ed25519"));
        assert!(!content.contains("Port 22"));
    }

    #[test]
    fn render_includes_certificate_file() {
        let store = LauncherStore::open_in_memory().unwrap();
        let default_id = store.get_identity_by_name("Default").unwrap().unwrap().id;
        store
            .update_identity(
                default_id,
                &crate::store::IdentityUpdate {
                    private_key: Some(Some(PathBuf::from("/home/user/.ssh/id_ed25519"))),
                    certificate: Some(Some(PathBuf::from("/home/user/.ssh/id_ed25519-cert.pub"))),
                    ..Default::default()
                },
            )
            .unwrap();

        store
            .create_host(&NewHost {
                name: "cert-host".into(),
                address: "10.0.0.1".into(),
                port: Some(22),
                identity_id: Some(default_id),
                ..Default::default()
            })
            .unwrap();

        let content = render_launcher_hosts(&store).unwrap();
        assert!(content.contains("IdentityFile /home/user/.ssh/id_ed25519"));
        assert!(content.contains("CertificateFile /home/user/.ssh/id_ed25519-cert.pub"));
    }

    #[test]
    fn render_includes_remote_command() {
        let store = LauncherStore::open_in_memory().unwrap();
        store
            .create_host(&NewHost {
                name: "tmux-host".into(),
                address: "10.0.0.1".into(),
                port: Some(22),
                remote_command: Some("tmux attach".into()),
                ..Default::default()
            })
            .unwrap();

        let content = render_launcher_hosts(&store).unwrap();
        assert!(content.contains("RemoteCommand=\"tmux attach\""));
    }

    fn launcher_host(
        store: &LauncherStore,
        name: &str,
        address: &str,
    ) -> crate::store::ManagedHost {
        store
            .create_host(&NewHost {
                name: name.into(),
                address: address.into(),
                port: Some(22),
                ..Default::default()
            })
            .unwrap()
    }

    #[test]
    fn export_refuses_an_invalid_proxy_jump() {
        let store = LauncherStore::open_in_memory().unwrap();
        let mut h = launcher_host(&store, "evil", "10.0.0.1");
        h.proxy_jump = Some("a$IFS-oProxyCommand=touch$IFS/tmp/x@h".into());
        let err =
            render_host_block(&h, &crate::store::ResolvedConnection::from_stored(&h)).unwrap_err();
        assert!(format!("{err:#}").contains("ProxyJump"), "{err:#}");
    }

    #[test]
    fn export_refuses_pattern_and_whitespace_values() {
        let store = LauncherStore::open_in_memory().unwrap();
        for (n, name) in ["*", "a *", "a,b", "!x", "a b"].into_iter().enumerate() {
            let h = launcher_host(&store, &format!("ok{n}"), "10.0.0.1");
            let h = crate::store::ManagedHost {
                name: name.into(),
                ..h
            };
            let r = crate::store::ResolvedConnection::from_stored(&h);
            assert!(render_host_block(&h, &r).is_err(), "name {name:?}");
        }
        let mut h = launcher_host(&store, "ws", "10.0.0.1");
        h.address = "10.0.0.1 extra".into();
        let r = crate::store::ResolvedConnection::from_stored(&h);
        assert!(render_host_block(&h, &r).is_err());
    }

    #[test]
    fn export_escapes_percent_and_quotes_spaced_paths() {
        let mut p = PathBuf::from("/home/Mary Ann/.ssh/id%h");
        assert_eq!(
            path_val("IdentityFile", &p).unwrap(),
            "\"/home/Mary Ann/.ssh/id%%h\""
        );
        p = PathBuf::from("/k/id");
        assert_eq!(path_val("IdentityFile", &p).unwrap(), "/k/id");
    }

    #[test]
    fn export_skips_ssh_config_rows() {
        let store = LauncherStore::open_in_memory().unwrap();
        store
            .upsert_ssh_config_host(&crate::store::SshConfigHostImport {
                name: "imported".into(),
                address: "10.0.0.9".into(),
                port: 22,
                proxy_jump: None,
                forward_agent: false,
                remote_command: None,
                ssh_config_hash: "hash".into(),
                tags: vec![],
                notes: None,
                environment: None,
                favorite: false,
                last_connected: None,
                ..Default::default()
            })
            .unwrap();

        let content = render_launcher_hosts(&store).unwrap();
        assert_eq!(content, EXPORT_HEADER);
    }

    #[test]
    fn atomic_write_creates_backup() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("exported.conf");
        atomic_write_with_backup(&path, "first\n").unwrap();
        atomic_write_with_backup(&path, "second\n").unwrap();

        assert_eq!(fs::read_to_string(&path).unwrap(), "second\n");
        let bak = backup_path(&path);
        assert_eq!(fs::read_to_string(bak).unwrap(), "first\n");
    }
}
